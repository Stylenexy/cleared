import { readFile, writeFile } from "node:fs/promises";
import {
  KOPI_PAGI,
  KERTAS_KITA,
  KOPI_PAGI_LOOKALIKES,
  KERTAS_KITA_UPDATED,
} from "../web/lib/sample-addresses.ts";

// Static artifacts cannot import TypeScript; regenerate them from the same module.
const samples = [
  ["01-kopi", "KP-001", "Northwind Design Studio", KOPI_PAGI, "0.25"],
  ["02-kertas", "KK-002", "Ledgerline Audits", KERTAS_KITA, "0.40"],
  ["03-beracun", "KP-003", "Northwind Design Studio", KOPI_PAGI_LOOKALIKES[0], "0.15"],
];
for (const [file, , , address] of samples) {
  const target = `web/public/samples/${file}.txt`;
  const source = await readFile(target, "utf8");
  await writeFile(
    target,
    source.replace(/^Address: .+$/m, `Address: ${address}`),
  );
}
await writeFile(
  "web/public/samples/invoices.csv",
  "reference,name,payee,amount,currency\n" +
    samples
      .map(([, ref, name, address, amount]) =>
        [ref, name, address, amount, "tUSD8"].join(","),
      )
      .join("\n") +
    "\n",
);
const constants = {
  KOPI_PAGI,
  KERTAS_KITA,
  ...Object.fromEntries(
    KOPI_PAGI_LOOKALIKES.map((address, n) => [
      `KOPI_PAGI_LOOKALIKE_${n + 1}`,
      address,
    ]),
  ),
  KERTAS_KITA_UPDATED,
};
await writeFile(
  "contracts/test/SampleAddresses.sol",
  "// SPDX-License-Identifier: MIT\npragma solidity ^0.8.28;\n\n" +
    "// Generated by tools/sync-sample-addresses.mjs from web/lib/sample-addresses.ts.\n" +
    "// Fictional sample addresses from public seeds, never private keys.\n" +
    "library SampleAddresses {\n" +
    Object.entries(constants)
      .map(
        ([name, address]) =>
          `    address internal constant ${name} = ${address};\n`,
      )
      .join("") +
    "}\n",
);
// These exports are authored samples, not migrated receipts for old destinations.
const rows = samples.map(([, reference, name, payee, amount], n) => ({
  reference,
  name,
  payee,
  amount: String(Number(amount)),
  status: n < 2 ? "Simulated Paid" : "Simulated Name mismatch",
}));
await writeFile(
  "docs/local-proof.json",
  JSON.stringify(
    {
      network: "Sample simulation only",
      source: "web/lib/sample-addresses.ts",
      notice:
        "Authored sample. No transaction sent; no receipt or balance measured.",
      rows,
    },
    null,
    2,
  ) + "\n",
);
await writeFile(
  "docs/local-reconciliation.csv",
  [
    ["Reference", "Name", "Sample payee", "tUSD8", "Simulated result"],
    ...rows.map((row) => [
      row.reference,
      row.name,
      row.payee,
      row.amount,
      row.status,
    ]),
  ]
    .map((row) =>
      row.map((value) => `"${value.replaceAll('"', '""')}"`).join(","),
    )
    .join("\r\n") + "\r\n",
);
console.log(
  "Synchronized sample TXT, CSV, Foundry addresses and simulation exports.",
);
